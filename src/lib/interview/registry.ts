import type { Topic } from "../profile/fields";
import type { Predicate } from "./rules";

export type OutputKey =
  | "buyer_summary"
  | "area_fit"
  | "deposit_scenario"
  | "rental_cashflow"
  | "funding_ceiling"
  | "affordability_conclusion";

export type AnswerType =
  | "single_choice"
  | "money"
  | "money_period" // targets: [amount, frequency]
  | "number"
  | "percent"
  | "text"
  | "list"
  | "boolean"
  | "date";

export interface Question {
  key: string;
  version: number;
  topic: Topic;
  eligibleWhen?: Predicate;
  prerequisites: string[]; // field paths that must be answered first
  prompt: string;
  /** Short reason shown when helpful (CON01). */
  reason?: string;
  answerType: AnswerType;
  options?: { value: string; label: string }[];
  targets: string[];
  requiredFor: OutputKey[];
  /** Optional questions can be skipped without leaving a required gap. */
  optional: boolean;
  priority: number; // lower first
  onUnknown?: "mark_unresolved" | "record_unknown";
  /** Expanded once per existing property; `{i}` in prompt/targets/prerequisites is replaced. */
  perProperty?: boolean;
}

