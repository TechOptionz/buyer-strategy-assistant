export interface ExpandedQuestion extends Question {
  /** Concrete key, e.g. "property_value:2". */
  instanceKey: string;
  propertyIndex?: number;
}

export function expandQuestions(propertyIndexes: number[]): ExpandedQuestion[] {
  const out: ExpandedQuestion[] = [];
  for (const q of QUESTIONS) {
    if (!q.perProperty) {
      out.push({ ...q, instanceKey: q.key });
      continue;
    }
    for (const i of propertyIndexes) {
      const sub = (s: string) => s.replaceAll("{i}", String(i));
      out.push({
        ...q,
        instanceKey: `${q.key}:${i}`,
        propertyIndex: i,
        prompt: propertyIndexes.length === 1 ? sub(q.prompt).replace(`property ${i}`, "your existing property") : sub(q.prompt),
        targets: q.targets.map(sub),
        prerequisites: q.prerequisites.map(sub),
      });
    }
  }
  return out;
}

